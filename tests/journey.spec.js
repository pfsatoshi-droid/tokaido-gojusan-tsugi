import {test,expect} from '@playwright/test';
test('55 locations, filters, search, saved visits and notes',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.card')).toHaveCount(6);
 await page.getByRole('button',{name:'すべての宿場を見る'}).click();
 await expect(page.locator('.card')).toHaveCount(55);
 await page.getByRole('button',{name:'京都',exact:true}).click();
 await expect(page.locator('.card')).toHaveCount(1);
 await expect(page.locator('.card')).toContainText('三条大橋');
 await page.getByRole('button',{name:'すべて',exact:true}).click();
 await page.getByRole('searchbox').fill('箱根');
 await expect(page.locator('.card')).toHaveCount(1);
 await page.locator('.card').click();
 await expect(page.locator('dialog h2')).toHaveText('箱根');
 await page.locator('#note').fill('富士山がきれい！ <script>安全なメモ</script>');
 await page.getByRole('button',{name:'メモを保存'}).click();
 await page.getByRole('button',{name:'訪れた！ 足あとをつける'}).click();
 await page.getByRole('button',{name:'閉じる'}).click();
 await expect(page.locator('#count')).toHaveText('1');
 await page.reload();
 await page.getByRole('button',{name:'旅のきろく',exact:true}).click();
 await expect(page.locator('.card')).toHaveCount(1);
 await page.locator('.card').click();
 await expect(page.locator('#note')).toHaveValue('富士山がきれい！ <script>安全なメモ</script>');
 await page.getByRole('button',{name:'✓ 訪問済み（取り消す）'}).click();
 await page.keyboard.press('Escape');
 await expect(page.locator('#count')).toHaveText('0');
 await expect(page.locator('.empty')).toBeVisible();
 expect(errors).toEqual([]);
});
test('mobile layout and journey navigation',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'/tmp/tokaido-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'旅をはじめる'}).click();
 await expect(page.locator('dialog h2')).toHaveText('日本橋');
 await expect(page.locator('#prev')).toBeDisabled();
 await page.getByRole('button',{name:'次の宿場 →'}).click();
 await expect(page.locator('dialog h2')).toHaveText('品川');
 await page.getByRole('button',{name:'閉じる'}).click();
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'/tmp/tokaido-desktop.png',fullPage:true});
});
test('map shows route, filters pins, zooms and synchronizes visits',async({page})=>{
 await page.goto('/');
 await page.locator('#map-nav').click();
 await expect(page.locator('#journey-map')).toBeVisible();
 await expect(page.locator('#cards')).toBeHidden();
 await expect(page.locator('.map-pin:visible')).toHaveCount(55);
 await page.getByRole('button',{name:'地図を拡大',exact:true}).click();
 await expect(page.locator('#map-scale')).toHaveText('150%');
 await page.locator('#map-reset').click();
 await expect(page.locator('#map-scale')).toHaveText('100%');
 await page.getByRole('button',{name:'京都',exact:true}).click();
 await expect(page.locator('.map-pin:visible')).toHaveCount(1);
 await page.locator('[data-map-stop="54"]').click();
 await expect(page.locator('dialog h2')).toHaveText('三条大橋');
 await page.locator('#stamp').click();
 await page.locator('#close').click();
 await expect(page.locator('[data-map-stop="54"]')).toHaveClass(/is-visited/);
 await page.getByRole('button',{name:'すべて',exact:true}).click();
 await page.getByRole('searchbox').fill('箱根');
 await expect(page.locator('.map-pin:visible')).toHaveCount(1);
 await page.locator('#map-destination').selectOption('10');
 await expect(page.locator('dialog h2')).toHaveText('箱根');
 await page.locator('#close').click();
 await page.getByRole('searchbox').fill('存在しない宿');
 await expect(page.locator('#map-match')).toHaveText('該当する宿場がありません');
 await page.getByRole('searchbox').fill('');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.locator('#map-destination').selectOption('0');
 await expect(page.locator('dialog h2')).toHaveText('日本橋');
 await page.locator('#close').click();
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('#journey-map').screenshot({path:'/tmp/tokaido-map.png'});
 await page.reload();
 await page.locator('#map-nav').click();
 await expect(page.locator('[data-map-stop="54"]')).toHaveClass(/is-visited/);
});
